#!/usr/bin/env python3
"""Generate gateway/internal/rules/sqlkeywords_gen.go from sqlparse's keyword dicts.

The Go SQL analyzer emulates sqlparse's lexer. Keyword typing (DML vs DDL vs
plain Keyword vs Name) decides statement classification, so the table is
generated from the installed sqlparse rather than hand-copied.
"""
import sqlparse
from sqlparse import tokens as T
from sqlparse.lexer import Lexer

TYPES = {
    T.Keyword: "tkKeyword", T.Keyword.DML: "tkDML", T.Keyword.DDL: "tkDDL",
    T.Keyword.DCL: "tkDCL", T.Keyword.CTE: "tkCTE", T.Name.Builtin: "tkBuiltin",
    T.Name: "tkName", T.Operator: "tkOperator", T.Keyword.Order: "tkOrder",
}
seen = {}
for d in Lexer.get_default_instance()._keywords:
    for word, ttype in d.items():
        if word not in seen:
            seen[word] = TYPES.get(ttype, "tkKeyword")
lines = ["// Code generated by scripts/gen_sql_keywords.py from sqlparse %s. DO NOT EDIT." % sqlparse.__version__,
         "", "package rules", "", "var sqlKeywords = map[string]tokType{"]
for w in sorted(seen):
    if " " in w:
        continue  # never produced by the \\w[$#\\w]* rule
    lines.append(f'\t"{w}": {seen[w]},')
lines.append("}")
open("gateway/internal/rules/sqlkeywords_gen.go", "w").write("\n".join(lines) + "\n")
print(len(seen), "keywords")
