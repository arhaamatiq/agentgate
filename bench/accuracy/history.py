#!/usr/bin/env python3
"""Build the benchmark run history from committed artifacts.

Runs 001-007 come from the original suite's reports (agenttest/reports/),
parsed from each report's executive summary. Where a raw result file exists
(runs 003-007), the script also counts decisions the run left unscored
because AgentGate itself errored; the original reports silently excluded
them from recall and precision.

Gateway runs come from bench/results/accuracy/*.json.

Output: bench/results/HISTORY.md and bench/results/history.json
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / "agenttest" / "reports"

RUNS = [
    ("001", "AGENT_TEST_20260328_021002.md", None, "Baseline"),
    ("002", "AGENT_TEST_20260328_151316.md", None, "Recall-first rules; precision collapsed"),
    ("003", "AGENT_TEST_003_20260401_005029.md", "run_003_raw.json",
     "INVALID: no network in sandbox, 340/370 tool calls never generated"),
    ("004", "AGENT_TEST_004_20260401_021247.md", "run_004_raw.json", "SQL resource extraction, UNKNOWN tool handling"),
    ("005", "AGENT_TEST_005_20260401_044747.md", "run_005_raw.json", "Tier 2 scope gate"),
    ("006", "AGENT_TEST_006_20260401_143750.md", "run_006_raw.json", "False-positive root cause fixed"),
    ("007", "AGENT_TEST_007_20260401_152557.md", "run_007_raw.json", "Precision/recall rebalance"),
]

SUMMARY = re.compile(
    r"Recall: ([\d.]+)%\*\* \| \*\*Precision: ([\d.]+)%.*?TP: (\d+) \| FN: (\d+) \| FP: (\d+) \| TN: (\d+)", re.S)


def unscored(raw_name: str | None) -> int | None:
    if not raw_name:
        return None
    n = 0
    for r in json.loads((REPORTS / raw_name).read_text()):
        for item in (r["steps"] if r.get("test_type") == "multi_turn" else [r]):
            if item.get("classification") == "error":
                n += 1
    return n


def main() -> None:
    rows = []
    for run, report, raw, note in RUNS:
        m = SUMMARY.search((REPORTS / report).read_text())
        recall, precision, tp, fn, fp, tn = m.groups()
        tp, fn, fp, tn = int(tp), int(fn), int(fp), int(tn)
        rows.append({
            "run": run, "engine": "Python in-process", "source": f"agenttest/reports/{report}",
            "recall": float(recall), "precision": float(precision),
            "fp_rate": round(100 * fp / (fp + tn), 1) if fp + tn else None,
            "scored": tp + fn + fp + tn, "unscored": unscored(raw), "note": note,
        })
    for f in sorted((ROOT / "bench/results/accuracy").glob("*.json")):
        s = json.loads(f.read_text())
        if "metrics" not in s or s.get("set") != "dev":
            continue
        m = s["metrics"]
        rows.append({
            "run": s["label"], "engine": s.get("engine", "Go gateway (/v1/check) + gRPC judge"),
            "source": f"bench/results/accuracy/{f.name}", "set": s["set"],
            "recall": round(100 * m["recall"], 1), "precision": round(100 * m["precision"], 1),
            "fp_rate": round(100 * m["fp_rate"], 1) if m["fp_rate"] is not None else None,
            "scored": m["decisions"], "unscored": m["unscored"], "note": s.get("judge_mode") or s.get("judge", ""),
        })

    (ROOT / "bench/results/history.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = [
        "# Benchmark run history",
        "",
        "Generated by `bench/accuracy/history.py` from committed artifacts. Do not edit by hand.",
        "",
        "Runs 001-007 are the original development runs of the Python engine on the",
        "adversarial suite (180 scenarios, 370 test runs, 466 decisions). They are",
        "**development-set** numbers: the rules were iterated against this suite.",
        "\"Unscored\" counts decisions where AgentGate itself raised an error; the",
        "original reports excluded them from recall and precision without saying so.",
        "",
        "| Run | Engine | Set | Recall | Precision | FP rate | Scored | Unscored | Notes |",
        "|---|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        un = "n/a" if r["unscored"] is None else str(r["unscored"])
        fpr = "" if r["fp_rate"] is None else f"{r['fp_rate']}%"
        lines.append(f"| [{r['run']}]({'../../' + r['source']}) | {r['engine']} | {r.get('set', 'dev')} | "
                     f"{r['recall']}% | {r['precision']}% | {fpr} | {r['scored']} | {un} | {r['note']} |")
    (ROOT / "bench/results/HISTORY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
